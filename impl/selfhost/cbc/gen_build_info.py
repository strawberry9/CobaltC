#!/usr/bin/env python3
# Writes impl/selfhost/cbc/build_info.cb: what cobc knows when it is built
# (impl/cobc/build.rs, `include_str!`) that cbc, a CobaltC program, takes as
# constants: the diagnostics registry (spec/registry/diagnostics.md, which
# cobc's front end renders diagnostics from), the stamp of the runtime it is
# built against (`CBRT_STAMP`, for the stale-runtime check), and the
# directory of that runtime.
#
#   gen_build_info.py [--stamp STAMP] [--cbrt-dir DIR] [--check]
#
# The committed file has an empty stamp (no runtime is refused) and an empty
# directory (the runtime beside the executable, as cobc's);
# impl/selfhost/build.sh writes the stamp of the `libcbrt.a` beside the cobc
# that builds cbc, builds, and writes the committed form back. `--check`
# exits 1 when the committed file is not what this script writes.
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.abspath(os.path.join(here, "..", "..", ".."))
registry_path = os.path.join(root, "spec", "registry", "diagnostics.md")
out_path = os.path.join(here, "build_info.cb")


def literal(text):
    # A CobaltC string literal, in pieces of about 100 bytes, each ending
    # at a character's end (as `coby --prelude-summary` writes them).
    pieces = []
    cur = ""
    size = 0
    for c in text:
        if c == '"':
            cur += '\\"'
        elif c == "\\":
            cur += "\\\\"
        elif c == "\n":
            cur += "\\n"
        elif c == "\t":
            cur += "\\t"
        elif c == "\r":
            cur += "\\r"
        else:
            cur += c
        size += len(c.encode("utf-8"))
        if size >= 100:
            pieces.append('    "' + cur + '"')
            cur = ""
            size = 0
    if size > 0 or not pieces:
        pieces.append('    "' + cur + '"')
    return "\n".join(pieces)


def render(stamp, cbrt_dir):
    with open(registry_path, encoding="utf-8") as f:
        registry = f.read()
    return (
        "// Generated by impl/selfhost/cbc/gen_build_info.py; do not edit.\n"
        "// What cobc takes in when it is built (impl/cobc/build.rs, `include_str!`):\n"
        "// the runtime's stamp (`CBRT_STAMP`, empty: no runtime is refused), the\n"
        "// runtime's directory (empty: beside this executable) and the diagnostics\n"
        "// registry, spec/registry/diagnostics.md.\n"
        "\n"
        "export const str CBRT_STAMP = " + literal(stamp).strip() + ";\n"
        "export const str CBRT_DIR = " + literal(cbrt_dir).strip() + ";\n"
        "\n"
        "export const str REGISTRY_SRC =\n" + literal(registry) + ";\n"
    )


def main():
    stamp = ""
    cbrt_dir = ""
    check = False
    args = sys.argv[1:]
    while args:
        a = args.pop(0)
        if a == "--stamp" and args:
            stamp = args.pop(0)
        elif a == "--cbrt-dir" and args:
            cbrt_dir = args.pop(0)
        elif a == "--check":
            check = True
        else:
            sys.exit("usage: gen_build_info.py [--stamp STAMP] [--cbrt-dir DIR] [--check]")
    text = render(stamp, cbrt_dir)
    if check:
        with open(out_path, encoding="utf-8") as f:
            if f.read() != text:
                print("gen_build_info.py: build_info.cb is not current (run impl/selfhost/cbc/gen_build_info.py)")
                sys.exit(1)
        return
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


main()
