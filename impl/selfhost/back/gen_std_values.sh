#!/usr/bin/env bash
# Writes impl/selfhost/back/std_values.cb: the names `std`'s own function
# bodies use as values, as cobc's `used_as_value` collects them
# (`Gen::value_names` over the functions whose keys begin `std::`, printed
# under `COBALTC_STD_FN_VALUES`). cbc parses a `std` body only when it reaches
# one, so `refs4::used_as_value` takes this part as given instead of parsing
# every body of `std` to collect it. `--check` exits 1 when the committed file
# is not what this script writes. COBC names another cobc.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
impl=$(cd "$here/../.." && pwd)
cobc=${COBC:-$impl/target/release/cobc}
out=$here/std_values.cb
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
printf 'fn main() : u8\n{\n    return 0;\n}\n' > "$tmp/main.cb"
COBALTC_STD_FN_VALUES=1 "$cobc" --cc /bin/true -o "$tmp/main" "$tmp/main.cb" > "$tmp/names"
{
    echo '// Generated by impl/selfhost/back/gen_std_values.sh; do not edit.'
    echo '// The names `std`'"'"'s own function bodies use as values, as cobc'"'"'s'
    echo '// `used_as_value` collects them, each between spaces:'
    echo '// `refs4::used_as_value` takes them as given rather than parse every body'
    echo '// of `std` to collect them.'
    echo ''
    echo 'export const str STD_FN_VALUES ='
    awk 'BEGIN { line = "    \" " }
         { if (length(line) + length($0) + 1 > 100) { print line "\""; line = "    \"" } line = line $0 " " }
         END { print line "\";" }' "$tmp/names"
} > "$tmp/std_values.cb"
if [ "${1:-}" = "--check" ]; then
    if ! cmp -s "$tmp/std_values.cb" "$out"; then
        echo "gen_std_values.sh: $out is not current (run impl/selfhost/back/gen_std_values.sh)" >&2
        exit 1
    fi
    exit 0
fi
cp "$tmp/std_values.cb" "$out"
