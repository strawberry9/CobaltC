#!/usr/bin/env python3
# Writes impl/selfhost/back/header.cb from impl/cbrt/include/cbrt.h: the
# runtime's C interface, which every generated C file begins with (cobc's
# `HEADER`, `include_str!` of the same file). compare_c.sh checks it is
# current:  python3 -I impl/selfhost/back/gen_header.py [OUT]  (default: header.cb here)
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', '..', 'cbrt', 'include', 'cbrt.h')
text = open(src, encoding='utf-8').read()
out = ['// Generated by impl/selfhost/back/gen_header.py from impl/cbrt/include/cbrt.h; do not edit.',
       '// The runtime\'s C interface, which every generated C file begins with.',
       '',
       'export const str HEADER =']
def lit(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\t', '\\t') + '"'
parts = []
for line in text.split('\n')[:-1] if text.endswith('\n') else text.split('\n'):
    chunk = line + '\n'
    # Keep each literal well inside the formatter's width.
    while len(chunk) > 90:
        cut = 90
        parts.append(chunk[:cut]); chunk = chunk[cut:]
    parts.append(chunk)
if not text.endswith('\n'):
    parts[-1] = parts[-1][:-1]
for i, p in enumerate(parts):
    e = lit(p).replace('\n', '\\n')
    out.append('    ' + e + (';' if i == len(parts) - 1 else ''))
dst = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, 'header.cb')
open(dst, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
