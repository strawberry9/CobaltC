#!/usr/bin/env python3
# Writes the tables `std::database`'s `saslprep` (RFC 4013) reads into
# impl/std/database.cb, between its two marker lines, from Python's
# `unicodedata.ucd_3_2_0` and `stringprep` modules -- Unicode 3.2, the
# version stringprep (RFC 3454) and so SASLprep are defined over, which
# never changes; the decompositions as PostgreSQL's own SASLprep
# (src/common/saslprep.c) applies them (see `nfkd_table`). `--check` exits 1 when the committed tables are not what
# this script writes.
#
#   python3 impl/tools/gen_saslprep.py [--check]
import os
import stringprep
import sys
import unicodedata

UCD = unicodedata.ucd_3_2_0
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'std', 'database.cb')
BEGIN = '// ---- SASLprep tables: generated by impl/tools/gen_saslprep.py, do not edit ----\n'
END = '// ---- end of the SASLprep tables ----\n'
MAX = 0x110000
SURROGATES = range(0xD800, 0xE000)


def chars():
    for cp in range(MAX):
        if cp in SURROGATES:
            continue
        yield cp


def ranges(pred):
    out = []
    start = None
    for cp in range(MAX + 1):
        inside = cp < MAX and cp not in SURROGATES and pred(chr(cp))
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            out.append((start, cp - 1))
            start = None
    return ';'.join('%x-%x' % r if r[0] != r[1] else '%x' % r[0] for r in out) + ';'


def is_hangul_syllable(cp):
    return 0xAC00 <= cp <= 0xD7A3


def nfkd_table():
    # PostgreSQL normalises with the Unicode version it was built with, not
    # 3.2: the code points 3.2 assigns decompose the same in every version
    # since Unicode 4.1 (normalization stability), so `unicodedata` gives
    # them, and those differ from 3.2's only for the five CJK compatibility
    # ideographs Corrigendum #4 corrected (U+2F868, U+2F874, U+2F91F,
    # U+2F95F, U+2F9BF). A code point 3.2 leaves unassigned is refused
    # before its decomposition matters (table A.1), so it has no entry.
    entries = []
    for cp in chars():
        if is_hangul_syllable(cp) or stringprep.in_table_a1(chr(cp)):
            continue
        d = unicodedata.normalize('NFKD', chr(cp))
        if d != chr(cp):
            entries.append('%x=%s' % (cp, ','.join('%x' % ord(c) for c in d)))
    return ';'.join(entries) + ';'


def ccc_table():
    entries = []
    for cp in chars():
        if stringprep.in_table_a1(chr(cp)):
            continue
        c = UCD.combining(chr(cp))
        if c:
            entries.append('%x=%x' % (cp, c))
    return ';'.join(entries) + ';'


def compose_table():
    entries = []
    for cp in chars():
        if is_hangul_syllable(cp) or stringprep.in_table_a1(chr(cp)):
            continue
        d = UCD.decomposition(chr(cp))
        if not d or d.startswith('<'):
            continue
        parts = [int(x, 16) for x in d.split()]
        if len(parts) != 2:
            continue
        if UCD.normalize('NFC', chr(parts[0]) + chr(parts[1])) == chr(cp):
            entries.append('%x,%x=%x' % (parts[0], parts[1], cp))
    return ';'.join(entries) + ';'


def prohibited(c):
    return (stringprep.in_table_c12(c) or stringprep.in_table_c21(c) or stringprep.in_table_c22(c)
            or stringprep.in_table_c3(c) or stringprep.in_table_c4(c) or stringprep.in_table_c5(c)
            or stringprep.in_table_c6(c) or stringprep.in_table_c7(c) or stringprep.in_table_c8(c)
            or stringprep.in_table_c9(c))


def literal(name, doc, text):
    lines = ['// ' + doc, 'const str %s =' % name]
    chunk = 96
    pieces = [text[i:i + chunk] for i in range(0, len(text), chunk)] or ['']
    for i, p in enumerate(pieces):
        lines.append('    "%s"%s' % (p, ';' if i == len(pieces) - 1 else ''))
    return '\n'.join(lines) + '\n'


def main():
    parts = [
        '// From Python\'s unicodedata.ucd_3_2_0 and stringprep (Unicode 3.2, as RFC 3454 and\n'
        '// RFC 4013 define them; the decompositions with Corrigendum #4, as PostgreSQL applies\n'
        '// them). Only code points Unicode 3.2 assigns. Entries are hexadecimal code points,\n'
        '// each ended by `;`.\n',
        literal('SASLPREP_NFKD', 'The full compatibility decomposition (NFKD) of each code point that has one, Hangul syllables apart: `cp=d1,d2,...`.', nfkd_table()),
        literal('SASLPREP_CCC', 'The canonical combining class of each code point whose class is not 0: `cp=class`.', ccc_table()),
        literal('SASLPREP_COMPOSE', 'The primary composites, Hangul apart: `first,second=composite`.', compose_table()),
        literal('SASLPREP_B1', 'RFC 3454 table B.1, mapped to nothing: ranges `lo-hi` or single code points.', ranges(stringprep.in_table_b1)),
        literal('SASLPREP_C12', 'RFC 3454 table C.1.2, the non-ASCII spaces, mapped to U+0020.', ranges(stringprep.in_table_c12)),
        literal('SASLPREP_PROHIBITED', 'RFC 4013 section 2.3: tables C.1.2, C.2.1, C.2.2 and C.3 to C.9 of RFC 3454.', ranges(prohibited)),
        literal('SASLPREP_UNASSIGNED', 'RFC 3454 table A.1, the code points unassigned in Unicode 3.2.', ranges(stringprep.in_table_a1)),
        literal('SASLPREP_RANDAL', 'RFC 3454 table D.1, the characters with bidirectional property R or AL.', ranges(stringprep.in_table_d1)),
        literal('SASLPREP_L', 'RFC 3454 table D.2, the characters with bidirectional property L.', ranges(stringprep.in_table_d2)),
    ]
    tables = '\n'.join(parts)
    with open(OUT) as f:
        old = f.read()
    a = old.index(BEGIN) + len(BEGIN)
    b = old.index(END)
    text = old[:a] + tables + old[b:]
    if len(sys.argv) > 1 and sys.argv[1] == '--check':
        if text != old:
            print('gen_saslprep.py: the tables in %s are not current (run impl/tools/gen_saslprep.py)' % OUT, file=sys.stderr)
            sys.exit(1)
        return
    with open(OUT, 'w') as f:
        f.write(text)


if __name__ == '__main__':
    main()
