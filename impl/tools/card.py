#!/usr/bin/env python3
"""CARD.md: CobaltC on one page, for a reader (or a model) who knows C or Rust
and is about to write CobaltC (CHG-0447). Nothing in it is written twice:
every part is taken from where it is kept, and `--check` fails when CARD.md
is not what this script writes now (the gate's `records` unit runs it).

    python3 impl/tools/card.py           # write CARD.md at the repository root
    python3 impl/tools/card.py --check   # exit 1 if CARD.md differs

| Part | Taken from |
|---|---|
| Syntax | book/src/appendix-a-syntax.md |
| Coming from C or Rust | book/src/appendix-c-c-and-rust.md, and impl/tests/foreign_forms/expected.txt |
| The tools | impl/cobc/src/main.rs's HELP, impl/src/main.rs's usage |
| Diagnostics | spec/registry/diagnostics.md |
| The standard library | impl/tools/cobdoc.py (std's own `///` documentation) |

Python 3 standard library only.
"""

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import cobdoc  # noqa: E402

OUT = os.path.join(ROOT, "CARD.md")


def read(*parts):
    with open(os.path.join(ROOT, *parts), encoding="utf-8") as f:
        return f.read()


def body_of(md):
    """A chapter without its title, its headings one level down."""
    lines = md.split("\n")
    if lines and lines[0].startswith("# "):
        lines = lines[1:]
    out = []
    fence = False
    for line in lines:
        if line.startswith("```"):
            fence = not fence
        if not fence and line.startswith("#"):
            line = "#" + line
        out.append(line)
    return "\n".join(out).strip("\n")


def rust_string(src, name):
    """A Rust `const NAME: &str = "…";` literal's text (the forms this repo
    uses: one line, or `"\\` and a line break before the first line)."""
    m = re.search(r'const %s: &str = "(.*?)";\n' % name, src, re.S)
    if not m:
        sys.exit("card.py: no const %s" % name)
    text = m.group(1)
    if text.startswith("\\\n"):
        text = text[2:]
    out, k = [], 0
    while k < len(text):
        c = text[k]
        if c == "\\" and k + 1 < len(text):
            n = text[k + 1]
            out.append({"n": "\n", "t": "\t", '"': '"', "\\": "\\"}.get(n, "\\" + n))
            k += 2
            continue
        out.append(c)
        k += 1
    return "".join(out)


def coby_usage(src):
    lines = []
    m = re.search(r"let usage = \|\| \{\n(.*?)ExitCode::from\(2\)", src, re.S)
    for line in (m.group(1) if m else "").split("\n"):
        s = re.match(r'\s*eprintln!\("(.*)"\);\s*$', line)
        if s:
            lines.append(s.group(1).replace('\\"', '"'))
    return "\n".join(lines)


def foreign_forms():
    """The one-habit programs' first diagnostics (impl/tests/foreign_forms):
    `name | habit | first line`."""
    rows = []
    path = os.path.join(ROOT, "impl", "tests", "foreign_forms", "expected.txt")
    if not os.path.isfile(path):
        return rows
    for line in read("impl", "tests", "foreign_forms", "expected.txt").split("\n"):
        parts = line.split(" | ", 2)
        if len(parts) != 3:
            continue
        msg = re.sub(r"^(error|fault)\[(diag\.[a-z-]+)\]: ", "", parts[2])
        rows.append((parts[1], msg))
    rows.sort()
    return rows


def diagnostics():
    """Each registry entry: its id, summary, phase and repair."""
    out = []
    lines = [l for l in read("spec", "registry", "diagnostics.md").split("\n") if l.startswith("- `diag.")]
    for line in lines:
        m = re.match(r"^- ((?:`diag\.[a-z0-9-]+`(?:, )?)+) — Summary: (.*?)\. Phase: (\w+).*?Repair: (.*?)(?:\. Location:.*|\.?)$", line)
        if not m:
            sys.exit("card.py: a registry entry this script cannot read: %s" % line[:80])
        out.append(m.groups())
    return out


def esc_cell(s):
    return s.replace("|", "\\|")


def card():
    a = read("book", "src", "appendix-a-syntax.md")
    c = read("book", "src", "appendix-c-c-and-rust.md")
    cobc = read("impl", "cobc", "src", "main.rs")
    coby = read("impl", "src", "main.rs")
    out = []
    w = out.append
    w("# CobaltC on one page")
    w("")
    w("Generated by `impl/tools/card.py` from the book, the tools' own help, the diagnostic registry and the")
    w("standard library's documentation; do not edit it here. Each part names where it comes from. The language")
    w("guide (`htmlguide/index.html`) and the book (`book/`) explain; this card is for looking things up while")
    w("writing.")
    w("")
    w("Three habits save the most time: write every type (`i32 x = 1;`, `auto x = 1;`), call functions with their")
    w("type's name (`Vec::push(&mut v, x)`; there is no method-call syntax), and convert by name (`widen`,")
    w("`narrow`, `to_float`, `to_int`). `cobc --check FILE.cb` reports every independent error in one run;")
    w("`cobc --doc NAME` shows any item of the standard library.")
    w("")
    w("## Syntax")
    w("")
    w("From `book/src/appendix-a-syntax.md`.")
    w("")
    w(body_of(a))
    w("")
    w("## Coming from C or Rust")
    w("")
    w("From `book/src/appendix-c-c-and-rust.md`.")
    w("")
    w(body_of(c))
    w("")
    rows = foreign_forms()
    if rows:
        w("### What the compiler says to another language's habit")
        w("")
        w("From `impl/tests/foreign_forms/expected.txt`: one short program per habit, and the first line of the")
        w("diagnostic it gets (the message names the CobaltC form).")
        w("")
        w("| Habit | Message |")
        w("|---|---|")
        for habit, msg in rows:
            w("| %s | %s |" % (esc_cell(habit), esc_cell(msg)))
        w("")
    w("## The tools")
    w("")
    w("From `impl/cobc/src/main.rs` (`cobc --help`) and `impl/src/main.rs` (`coby`'s usage).")
    w("")
    w("```")
    w(rust_string(cobc, "USAGE"))
    w("```")
    w("")
    w("```")
    w(rust_string(cobc, "HELP").rstrip("\n"))
    w("```")
    w("")
    w("```")
    w(coby_usage(coby))
    w("```")
    w("")
    w("## Diagnostics")
    w("")
    w("From `spec/registry/diagnostics.md`: each id, its summary (the message when the occurrence gives none),")
    w("its phase and its repair. `--explain` shows the whole entry.")
    w("")
    w("| Id | Summary | Phase | Repair |")
    w("|---|---|---|---|")
    for d, s, p, r in diagnostics():
        w("| %s | %s | %s | %s |" % (d, esc_cell(s), p, esc_cell(r)))
    w("")
    w("## The standard library")
    w("")
    w("From `impl/tools/cobdoc.py`: every exported item of `std`, by module, with its signature and the first")
    w("sentence of its documentation. `cobc --doc NAME` shows the whole entry and its examples; a removed name")
    w("is left out.")
    items = []
    cobdoc.items_of(cobdoc.STD, "std", items, set())
    items += cobdoc.builtins()
    mods = []
    for x in items:
        if x["module"] not in mods:
            mods.append(x["module"])
    for m in sorted(mods):
        w("")
        w("### %s" % m)
        w("")
        for x in items:
            if x["module"] != m or (x.get("retired") or {}).get("kind") == "removed":
                continue
            dep = " (deprecated)" if (x.get("retired") or {}).get("kind") == "deprecated" else ""
            summ = x["summary"] or ""
            w("- `%s`%s%s" % (x["signature"], dep, (" — " + summ) if summ else ""))
    w("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description="Write CARD.md, CobaltC on one page, from the sources it names.")
    ap.add_argument("--check", action="store_true", help="exit 1 if CARD.md is not what this writes")
    a = ap.parse_args()
    text = card()
    if a.check:
        have = open(OUT, encoding="utf-8").read() if os.path.isfile(OUT) else ""
        if have != text:
            print("card.py: CARD.md is not current: run python3 impl/tools/card.py", file=sys.stderr)
            return 1
        print("card.py: CARD.md is current (%d lines)" % text.count("\n"))
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("card.py: wrote CARD.md (%d lines)" % text.count("\n"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
