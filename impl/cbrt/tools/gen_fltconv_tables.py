#!/usr/bin/env python3
# Writes src/fltconv_tables.h: the powers of five the float text needs
# (src/fltconv.c). Run as `python3 -I tools/gen_fltconv_tables.py OUT`.
#
# - RYU_POW5_INV / RYU_POW5: Ryu's tables for the shortest digits
#   (Ulf Adams, "Ryu: fast float-to-string conversion", PLDI 2018), with
#   125-bit multipliers: 5^-i scaled up and 5^i scaled down to 125 bits.
# - LEMIRE_POW5: the Eisel-Lemire table for reading text (Lemire, "Number
#   Parsing at a Gigabyte per Second", 2021): 5^q for q in [-342, 308],
#   normalized to 128 bits, truncated (q >= 0) or rounded up (q < 0), as
#   Rust's `core::num::dec2flt::table` holds it.

import sys

POW5_INV_BITCOUNT = 125
POW5_BITCOUNT = 125


def split(v):
    return (v & ((1 << 64) - 1), v >> 64)


def ryu_tables():
    inv = []
    for i in range(342):
        p = 5 ** i
        j = p.bit_length() - 1 + POW5_INV_BITCOUNT
        inv.append((1 << j) // p + 1)
    fwd = []
    for i in range(326):
        p = 5 ** i
        j = p.bit_length() - POW5_BITCOUNT
        fwd.append(p >> j if j >= 0 else p << -j)
    return inv, fwd


def lemire_table():
    out = []
    for q in range(-342, 0):
        p5 = 5 ** -q
        z = 0
        while (1 << z) < p5:
            z += 1
        if q >= -27:
            b = z + 127
            c = 2 ** b // p5 + 1
        else:
            b = 2 * z + 2 * 64
            c = 2 ** b // p5 + 1
            while c >= (1 << 128):
                c //= 2
        out.append(c)
    for q in range(0, 309):
        p5 = 5 ** q
        while p5 < (1 << 127):
            p5 *= 2
        while p5 >= (1 << 128):
            p5 //= 2
        out.append(p5)
    return out


def emit(f, name, vals):
    f.write("static const uint64_t %s[%d][2] =\n{\n" % (name, len(vals)))
    for v in vals:
        lo, hi = split(v)
        f.write("    {0x%016xu, 0x%016xu},\n" % (lo, hi))
    f.write("};\n\n")


def main():
    out = sys.argv[1]
    inv, fwd = ryu_tables()
    lem = lemire_table()
    with open(out, "w") as f:
        f.write("/* Generated by tools/gen_fltconv_tables.py; do not edit. Each entry\n"
                "   is {low 64 bits, high 64 bits}. */\n\n")
        f.write("#define RYU_POW5_INV_BITCOUNT %d\n#define RYU_POW5_BITCOUNT %d\n\n" % (POW5_INV_BITCOUNT, POW5_BITCOUNT))
        emit(f, "RYU_POW5_INV", inv)
        emit(f, "RYU_POW5", fwd)
        f.write("/* 5^q for q in [-342, 308]: index q + 342. */\n")
        emit(f, "LEMIRE_POW5", lem)


main()
