# Go / Python / Java / JS
case("go_func", "Go: func", "", "func f() int { return 1 }")
case("go_short_decl", "Go: :=", "x := 1;")
case("go_nil", "Go: nil", "Option<i32> o = nil;")
case("py_def", "Python: def", "", "def f():\n    return 1")
case("py_none", "Python: None as value", "Option<i32> o = None;\n    i32 x = None;")
case("py_elif", "Python: elif", "i32 a = 1;\n    if (a == 1) { } elif (a == 2) { }")
case("py_len", "Python/Go: len(v)", "Vec<u8> v = Vec::new();\n    usize n = len(v);")
case("py_and", "Python: and / or / not", "bool a = true;\n    bool b = a and true;")
case("java_null", "Java/JS: null", "Option<i32> o = null;")
case("js_var", "JS: var", "var x = 1;")
case("js_const_infer", "JS/Rust: const without type", "", "const N = 3;")
case("java_string_equals", "Java: .equals", "String a = String::copy(\"a\");\n    bool b = a.equals(\"a\");")
# Names
case("nm_vec_psh", "name: Vec::psh", "Vec<u8> v = Vec::new();\n    Vec::psh(&mut v, 1);")
case("nm_vec_length", "name: Vec::length", "Vec<u8> v = Vec::new();\n    usize n = Vec::length(&v);")
case("nm_vec_size", "name: Vec::size", "Vec<u8> v = Vec::new();\n    usize n = Vec::size(&v);")
case("nm_vec_push_back", "name: Vec::push_back", "Vec<u8> v = Vec::new();\n    Vec::push_back(&mut v, 1);")
case("nm_vec_append_one", "name: Vec::add", "Vec<u8> v = Vec::new();\n    Vec::add(&mut v, 1);")
case("nm_view_size", "name: StringView::size", "StringView s = \"a\";\n    usize n = StringView::size(s);")
case("nm_string_length", "name: String::length", "String s = String::copy(\"a\");\n    usize n = String::length(&s);")
case("nm_hashmap_put", "name: HashMap::put", "HashMap<u32, u32> m = HashMap::new();\n    HashMap::put(&mut m, 1, 2);")
case("nm_print", "name: print", "print(\"a\");")
case("nm_printn", "name: printn (typo of printf)", "printn(\"a\");")
case("nm_local_typo", "name: a local misspelt", "usize count = 1;\n    usize b = coutn + 1;")
case("nm_type_typo", "name: a type misspelt", "Vect<u8> v = Vec::new();")
case("nm_strng", "name: Strng", "Strng s = String::copy(\"a\");")
case("nm_fn_typo", "name: a function misspelt", "usize x = sqaure(2);", "fn square(usize x) : usize { x * x }")
case("nm_option_unwrap_or_default", "name: Option::unwrap_or_default", "Option<i32> o = None;\n    i32 x = Option::unwrap_or_default(o);")
case("nm_vec_contains", "name: Vec::includes", "Vec<u8> v = Vec::new();\n    bool b = Vec::includes(&v, 1);")

for name, habit, pre, body in C:
    if body.startswith(("fn ", "struct ", "impl ", "use ", "pub ", "#", "int main", "void ", "const ", "typedef", "class", "namespace", "template", "func ", "def ")):
        text = "// %s\nimport std;\n%s%s\nfn main()\n{\n}\n" % (habit, pre + "\n" if pre else "", body)
        if body.startswith(("int main", "fn main")):
            text = "// %s\nimport std;\n%s\n" % (habit, body)
    else:
        text = "// %s\nimport std;\n%sfn main()\n{\n    %s\n}\n" % (habit, pre + "\n" if pre else "", body)
    with open(os.path.join(HERE, "cases", name + ".cb"), "w") as f:
        f.write(text)
print(len(C), "cases")
