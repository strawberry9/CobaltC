#!/usr/bin/env python3
"""Writes the one-habit programs of the foreign-forms experiment (CHG-0445): each
is a short CobaltC program with one form from another language in it, the habit
it tests named in its first line. Run once; `run.sh` checks them."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
C = []
def case(name, habit, body, pre=""):
    C.append((name, habit, pre, body))

# Rust
case("rs_let", "Rust: let", "let x = 1;\n    assert(x == 1);")
case("rs_let_mut", "Rust: let mut", "let mut x = 1;\n    x = 2;")
case("rs_arrow_ret", "Rust: -> return type", "", "fn f() -> i32 { 1 }")
case("rs_method_push", "Rust: method call", "Vec<u8> v = Vec::new();\n    v.push(1);")
case("rs_method_len", "Rust: method call, no args", "Vec<u8> v = Vec::new();\n    usize n = v.len();")
case("rs_println_macro", "Rust: println!", "println!(\"{}\", 1);")
case("rs_println", "Rust: println without !", "usize x = 1;\n    println(\"{}\", x);")
case("rs_suffix", "Rust: integer suffix", "usize a = 2usize;")
case("rs_as_cast", "Rust: as cast", "u32 a = 2;\n    u64 b = a as u64;")
case("rs_match_arrow", "Rust: match arms with =>", "i32 x = 1;\n    i32 y = match (x) { 1 => 2, _ => 3 };")
case("rs_match_noparen", "Rust: match without parentheses", "i32 x = 1;\n    i32 y = match x { 1 : 2, _ : 3 };")
case("rs_for_in", "Rust: for in range", "usize t = 0;\n    for i in 0..10 { t += i; }")
case("rs_loop", "Rust: loop", "usize t = 0;\n    loop { t += 1; if (t > 3) { break; } }")
case("rs_impl", "Rust: impl block", "", "struct P { i32 a; }\nimpl P { fn new() : P { P { .a = 1 } } }")
case("rs_vec_macro", "Rust: vec!", "Vec<u8> v = vec![1, 2];")
case("rs_struct_colon", "Rust: struct literal with field: value", "P p = P { a: 1 };", "struct P { i32 a; }")
case("rs_use", "Rust: use", "", "use std::collections;")
case("rs_pub", "Rust: pub fn", "", "pub fn f() : i32 { 1 }")
case("rs_closure_bars", "Rust: |x| closure", "auto f = |x| x + 1;")
case("rs_ref_str", "Rust: &str type", "", "fn f(&str s) : usize { 1 }")
case("rs_i32_max", "Rust: i32::MAX", "i32 m = i32::MAX;")
case("rs_while_let", "Rust: while let", "Option<i32> o = None;\n    while let Some(x) = o { o = None; }")
case("rs_if_let", "Rust: if let", "Option<i32> o = None;\n    if let Some(x) = o { }")
case("rs_assert_eq", "Rust: assert_eq!", "assert_eq!(1, 1);")
case("rs_assert_eq_fn", "Rust: assert_eq without !", "assert_eq(1, 1);")
case("rs_unwrap_method", "Rust: .unwrap()", "Option<i32> o = Some(1);\n    i32 x = o.unwrap();")
case("rs_ref_type", "Rust: &T parameter type", "", "fn f(&Vec<u8> v) : usize { 1 }")
case("rs_string_from", "Rust: String::from", "String s = String::from(\"a\");")
case("rs_to_string", "Rust: .to_string()", "String s = \"a\".to_string();")
case("rs_clone_method", "Rust: .clone()", "String a = String::copy(\"a\");\n    String b = a.clone();")
case("rs_mut_param", "Rust: mut parameter", "", "fn f(mut i32 x) : i32 { x }")
case("rs_unit_ret", "Rust: -> () ", "", "fn f() -> () { }")
case("rs_self", "Rust: self parameter", "", "struct P { i32 a; }\nfn P::get(self) : i32 { 1 }")
case("rs_semicolon_tail", "Rust: tail with ;", "", "fn f() : i32 { 1; }")
# C / C++
case("c_int", "C: int", "int x = 1;")
case("c_incr", "C: x++", "i32 x = 1;\n    x++;")
case("c_printf_d", "C: %d", "i32 x = 1;\n    printf(\"%d\\n\", x);")
case("c_char_star", "C: char *", "char *s = \"a\";")
case("c_null", "C: NULL", "Option<Box<i32>> p = NULL;")
case("c_include", "C: #include", "", "#include <stdio.h>")
case("c_struct_init", "C: struct P p = {1}", "struct P p = {1};", "struct P { i32 a; }")
case("c_cast", "C: (T)x cast", "u32 a = 2;\n    u64 b = (u64)a;")
case("c_sizeof", "C: sizeof", "usize n = sizeof(u64);")
case("c_ternary", "C: ?:", "i32 a = 1;\n    i32 b = a > 0 ? 1 : 2;")
case("c_do_while", "C: do while", "i32 a = 0;\n    do { a += 1; } while (a < 3);")
case("c_switch", "C: switch", "i32 a = 0;\n    switch (a) { case 0: break; }")
case("c_array_decl", "C: int a[10]", "i32 a[10];")
case("c_malloc", "C: malloc", "u8 p = malloc(10);")
case("c_int_main", "C: int main", "", "int main() { return 0; }", )
case("c_void_ret", "C: void f()", "", "void f() { }")
case("c_const_int", "C: const int", "", "const int N = 3;")
case("c_typedef", "C: typedef", "", "typedef u32 Word;")
case("c_define", "C: #define", "", "#define N 3")
case("c_arrow", "C: p->field", "P p = P { .a = 1 };\n    ref<P, shared> r = &p;\n    i32 x = r->a;", "struct P { i32 a; }")
case("c_char_lit", "C: 'a' char literal", "u8 c = 'a';")
case("c_goto", "C: goto", "goto done;")
case("c_unsigned", "C: unsigned int", "unsigned int x = 1;")
case("c_double", "C: double", "double x = 1.0;")
case("c_bool_not_int", "C: !n on an integer", "u16 m = 1;\n    u16 n = !m;")
case("c_struct_semi", "C: struct ends with ;", "", "struct P { i32 a; };")
case("c_main_args", "C: main(argc, argv)", "fn main(i32 argc, str argv) { }")
case("c_mixed_ints", "C: mixed integer widths", "u32 a = 1;\n    u64 b = 2;\n    u64 c = a + b;")
case("c_float_div_int", "C: integer to float", "i32 a = 1;\n    f64 b = a / 2.0;")
case("cpp_auto_for", "C++: for (auto x : v)", "Vec<u8> v = Vec::new();\n    for (auto x : v) { }")
case("cpp_std_vector", "C++: std::vector", "std::vector<u8> v;")
case("cpp_new", "C++/Java: new", "Box<i32> b = new Box<i32>(1);")
case("cpp_nullptr", "C++: nullptr", "Option<Box<i32>> p = nullptr;")
case("cpp_class", "C++/Java: class", "", "class C { }")
